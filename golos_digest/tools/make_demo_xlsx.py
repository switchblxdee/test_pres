SOURCES = [f"Канал поддержки {i}" for i in range(1, 17)]
start = date(2026, 10, 9)


def main(path: str) -> None:
    markup = []
    for product, topic, cur, _prev, _st, msgs in TOPICS:
        for i in range(cur):
            markup.append({
                "Дата сигнала от клиента": start + timedelta(days=random.randint(0, 6)),
                "источник сигнала": random.choice(SOURCES),
                "Объект сигнала": product,
                "Кластер сигналов 2 уровня": topic,
                "Текст из источника обратной связи": msgs[i % len(msgs)] if i < len(msgs) else random.choice(msgs),
            })
    summary = []
    for product, topic, cur, prev, status, _ in TOPICS:
        summary.append({
            "продукт": product, "тема": topic, "сигналы текущей недели": cur, "сигналы прошлой недели": prev,
            "динамика %": (f"{round((cur - prev) / prev * 100)}%" if prev else ""), "статус": status,
            "динамика кол-во": cur - prev, "Дата выпуска": date(2026, 10, 16), "Период": "09.10 – 15.10",
            "Номер": 20, "Кол-во проанализированных сигналов": 433, "Кол-во источников": 16,
        })
    with pd.ExcelWriter(path) as xw:
        pd.DataFrame(markup).to_excel(xw, sheet_name="разметка", index=False)
        pd.DataFrame(summary).to_excel(xw, sheet_name="свод", index=False)
    print(path)


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "demo.xlsx")
